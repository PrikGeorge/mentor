import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import { provideHttpClientTesting } from '@angular/common/http/testing';
import { EditorPanelComponent, ResetKind } from './editor-panel.component';
import { MonacoLoader } from './monaco-loader.service';
import type { Mode } from './practice-api.service';
describe('Editor panel', () => {
    afterEach(() => TestBed.resetTestingModule());
    async function setup(inputs: Record<string, unknown> = {}) {
        TestBed.configureTestingModule({ imports: [EditorPanelComponent], providers: [provideHttpClient(), provideHttpClientTesting(), { provide: MonacoLoader, useValue: { load: () => Promise.reject(new Error('fixture fallback')) } }] });
        const fixture = TestBed.createComponent(EditorPanelComponent);
        const values = { files: { 'Task.java': 'class Task {}', 'Util.java': 'class Util {}' }, file: 'Task.java', editorContext: 'l1:e1:Task.java', writable: true, runnable: true, ...inputs };
        for (const [name, value] of Object.entries(values)) fixture.componentRef.setInput(name, value);
        fixture.detectChanges();
        await fixture.whenStable();
        fixture.detectChanges();
        return { fixture, element: fixture.nativeElement as HTMLElement, component: fixture.componentInstance };
    }
    const button = (element: HTMLElement, text: string) => Array.from(element.querySelectorAll('button')).find(node => node.textContent?.trim() === text);
    it('lists the files as tabs, shows the current one in the editor and reports edits with the file name', async () => {
        const { fixture, element, component } = await setup();
        const tabs = Array.from(element.querySelectorAll<HTMLButtonElement>('.practice-files button'));
        expect(tabs.map(tab => tab.textContent)).toEqual(['Task.java', 'Util.java']);
        expect(tabs.map(tab => tab.getAttribute('aria-pressed'))).toEqual(['true', 'false']);
        const chosen: string[] = [], edits: { name: string; text: string }[] = [];
        component.fileChosen.subscribe(name => chosen.push(name));
        component.edited.subscribe(edit => edits.push(edit));
        tabs[1].click();
        expect(chosen).toEqual(['Util.java']);
        const textarea = element.querySelector<HTMLTextAreaElement>('textarea')!;
        expect(textarea.value).toBe('class Task {}');
        textarea.value = 'class Task { int x; }';
        textarea.dispatchEvent(new Event('input'));
        expect(edits).toEqual([{ name: 'Task.java', text: 'class Task { int x; }' }]);
        fixture.destroy();
    });
    it('offers save, export, run and the revision choice to the owner and reports each action', async () => {
        const { fixture, element, component } = await setup({ compatible: false, dirty: true });
        let saves = 0, exports = 0;
        const runs: Mode[] = [], resets: ResetKind[] = [];
        component.saveRequested.subscribe(() => saves++);
        component.exportRequested.subscribe(() => exports++);
        component.runRequested.subscribe(mode => runs.push(mode));
        component.resetChosen.subscribe(kind => resets.push(kind));
        expect(element.querySelector('.draft-state')?.textContent).toBe('Есть несохранённые изменения');
        expect(element.textContent).toContain('Упражнение обновилось, а твой код остался на прежней версии.');
        expect(button(element, 'Сохранить код')?.disabled).toBe(true);
        button(element, 'Скачать код')!.click();
        element.querySelector<HTMLButtonElement>('[data-action=run]')!.click();
        element.querySelector<HTMLButtonElement>('[data-action=submit]')!.click();
        button(element, 'Перенести мой код')!.click();
        button(element, 'Взять новые заготовки')!.click();
        expect({ saves, exports, runs, resets }).toEqual({ saves: 0, exports: 1, runs: ['run', 'submit'], resets: ['keep', 'template'] });
        fixture.componentRef.setInput('compatible', true);
        fixture.componentRef.setInput('busy', true);
        fixture.detectChanges();
        expect(element.querySelector('.draft-state')?.textContent).toBe('Сохраняем…');
        fixture.componentRef.setInput('busy', false);
        fixture.componentRef.setInput('dirty', false);
        fixture.detectChanges();
        expect(element.querySelector('.draft-state')?.textContent).toBe('Черновик сохранён');
        button(element, 'Сохранить код')!.click();
        expect(saves).toBe(1);
        fixture.destroy();
    });
    it('is read-only for a viewer: no save or run controls, export only for the source owner, draft errors still visible', async () => {
        const { fixture, element } = await setup({ writable: false, exportable: false, readonly: true, draftError: 'Черновик или упражнение изменились.' });
        expect(element.querySelector('[data-action=run]')).toBeNull();
        expect(element.querySelector('[data-action=submit]')).toBeNull();
        expect(button(element, 'Сохранить код')).toBeUndefined();
        expect(button(element, 'Скачать код')).toBeUndefined();
        expect(element.textContent).toContain('только чтение');
        expect(element.querySelector('.practice-editor .auth-error')?.textContent).toBe('Черновик или упражнение изменились.');
        expect(element.querySelector('textarea')?.readOnly).toBe(true);
        fixture.componentRef.setInput('exportable', true);
        fixture.detectChanges();
        expect(button(element, 'Скачать код')).toBeDefined();
        fixture.destroy();
    });
    it('names the open file instead of tabs when the trainer tree lists the files', async () => {
        const { fixture, element } = await setup({ tabs: false });
        expect(element.querySelector('.practice-files')).toBeNull();
        expect(element.querySelector('.practice-file-name')?.textContent).toBe('Task.java');
        expect(element.querySelector('textarea')?.getAttribute('wrap')).toBe('off');
        fixture.destroy();
    });
});
