import { TestBed } from '@angular/core/testing';
import { NavigationEnd } from '@angular/router';
import { filter, firstValueFrom } from 'rxjs';
import { renderResources, configure, open, page, student, lesson, base, click, fill, publicStudent, publicLesson, flushTurns } from '../students/domain-test-support';
describe('Lesson creation and preparation', () => {
    beforeEach(configure);
    afterEach(() => TestBed.resetTestingModule());
    it('does not open an old lesson editor in a new teacher workspace before view teardown', async () => {
        const { fixture, http, session, element } = await open('/teacher/students/s1/lessons/l1');
        http.expectOne(base).flush(student); http.expectOne(base + '/lessons/l1').flush(lesson); await renderResources(); fixture.detectChanges();
        session.load().subscribe(); http.expectOne('/api/v1/auth/session').flush({ account: { userId: 'another-teacher', workspaceId: 'w2', role: 'TEACHER', authVersion: 1 }, csrfToken: 'synthetic-new' });
        click(element, 'Изменить сценарий'); http.expectNone(request => request.url.includes('/texts/'));
        await renderResources(); fixture.detectChanges(); http.match(request => request.method === 'GET').forEach(request => { if (!request.cancelled) request.flush({items:[],page:0,size:25,total:0}); });
    });
    it('creates only the short four-field form and navigates to preparation after 201', async () => {
        const { fixture, http, element, router } = await open('/teacher/students/s1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons?page=0&size=25').flush(page([]));
        await renderResources(); fixture.detectChanges();
        http.expectOne(base + '/access').flush({ account: null, invitation: null });
        await renderResources(); fixture.detectChanges();
        click(element, 'Добавить занятие');
        fixture.detectChanges();
        expect(element.querySelectorAll('form')).toHaveLength(1);
        expect(element.querySelector('[name="reviewNotes"]')).toBeNull();
        fill(element, 'title', 'Новая тема');
        fill(element, 'date', '2026-10-03');
        fill(element, 'time', '13:00');
        fill(element, 'duration', '90');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        const create = http.expectOne(base + '/lessons');
        expect(create.request.body).toEqual({ title: 'Новая тема', date: '2026-10-03', time: '13:00', duration: 90 });
        expect(create.request.body).not.toHaveProperty('reviewNotes');
        expect(router.url).toBe('/teacher/students/s1');
        const navigation = firstValueFrom(router.events.pipe(filter(event => event instanceof NavigationEnd)));
        create.flush({ ...lesson, title: 'Новая тема' }, { status: 201, statusText: 'Created' });
        await navigation;
        await renderResources(); fixture.detectChanges();
        expect(router.url).toBe('/teacher/students/s1/lessons/l1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons/l1').flush({ ...lesson, title: 'Новая тема' });
        await renderResources(); fixture.detectChanges();
        expect(element.textContent).toContain('Подготовка занятия');
        expect(element.querySelectorAll('h1')).toHaveLength(1);
        flushTurns(http); http.verify();
    });
    it('keeps entered short-form values and does not navigate after a creation error', async () => {
        const { fixture, http, element, router } = await open('/teacher/students/s1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons?page=0&size=25').flush(page([]));
        await renderResources(); fixture.detectChanges();
        http.expectOne(base + '/access').flush({ account: null, invitation: null });
        await renderResources(); fixture.detectChanges();
        click(element, 'Добавить занятие');
        fixture.detectChanges();
        fill(element, 'title', 'Не потерять');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        http.expectOne(base + '/lessons').flush({ message: 'Ошибка сохранения' }, { status: 400, statusText: 'Bad Request' });
        await renderResources(); fixture.detectChanges();
        expect(element.querySelector<HTMLInputElement>('[name="title"]')?.value).toBe('Не потерять');
        expect(router.url).toBe('/teacher/students/s1');
        flushTurns(http); http.verify();
    });
    it('teacher preview fetches public projection, keeps one header and offers no write controls', async () => {
        const { fixture, http, element, session } = await open('/teacher/students/s1/lessons/l1/student/tasks?preview=student');
        http.expectOne(base + '?audience=student').flush(publicStudent);
        http.expectOne(base + '/lessons/l1?audience=student').flush(publicLesson);
        await renderResources(); fixture.detectChanges();
        expect(session.actor()?.role).toBe('TEACHER');
        expect(element.querySelectorAll('h1')).toHaveLength(1);
        expect(element.textContent).toContain('Задания Анны');
        expect(element.textContent).not.toContain('Частный сценарий');
        expect(element.textContent).not.toContain('Частные заметки');
        expect(element.querySelector('form')).toBeNull();
        expect(Array.from(element.querySelectorAll('button')).some(b => /Сохранить|Изменить|Сдать/.test(b.textContent || ''))).toBe(false);
        flushTurns(http); http.verify();
    });
    it('loads and saves an independent text revision while preserving Markdown whitespace', async () => {
        const { fixture, http, element } = await open('/teacher/students/s1/lessons/l1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons/l1').flush(lesson);
        await renderResources(); fixture.detectChanges();
        click(element, 'Изменить сценарий');
        fixture.detectChanges();
        http.expectOne(base + '/lessons/l1/texts/teacherNotes').flush({ kind: 'teacherNotes', markdown: '  source  \n', revision: 7 });
        await renderResources(); fixture.detectChanges();
        fill(element, 'markdown', '  новое  \n');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        const save = http.expectOne(base + '/lessons/l1/texts/teacherNotes');
        expect(save.request.method).toBe('PUT');
        expect(save.request.body).toEqual({ markdown: '  новое  \n', revision: 7 });
        save.flush({ kind: 'teacherNotes', markdown: '  новое  \n', revision: 8 });
        await renderResources(); fixture.detectChanges();
        expect(element.querySelector('form')).toBeNull();
        flushTurns(http); http.verify();
    });
    it('keeps Markdown in the text editor on stale revision without changing lesson metadata', async () => {
        const { fixture, http, element } = await open('/teacher/students/s1/lessons/l1/teacher/review');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons/l1').flush(lesson);
        await renderResources(); fixture.detectChanges();
        http.expectOne(base + '/lessons/l1/homework?page=0&size=25').flush({items:[],page:0,size:25,total:0});
        await renderResources(); fixture.detectChanges();
        click(element, 'Изменить ревью');
        fixture.detectChanges();
        http.expectOne(base + '/lessons/l1/texts/reviewNotes').flush({ kind: 'reviewNotes', markdown: 'old', revision: 3 });
        await renderResources(); fixture.detectChanges();
        fill(element, 'markdown', '  сохранить локально\n');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        const save = http.expectOne(base + '/lessons/l1/texts/reviewNotes');
        expect(save.request.body).toEqual({ markdown: '  сохранить локально\n', revision: 3 });
        save.flush({ message: 'Ревизия устарела' }, { status: 409, statusText: 'Conflict' });
        await renderResources(); fixture.detectChanges();
        expect(element.querySelector<HTMLTextAreaElement>('[name="markdown"]')?.value).toBe('  сохранить локально\n');
        expect(element.textContent).toContain('Текст уже изменили в другой вкладке.');
        flushTurns(http); http.verify();
    });
    it('metadata form excludes all lesson texts and uses the metadata revision', async () => {
        const { fixture, http, element } = await open('/teacher/students/s1/lessons/l1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons/l1').flush({ ...lesson, revision: 5 });
        await renderResources(); fixture.detectChanges();
        click(element, 'Изменить занятие');
        fixture.detectChanges();
        fill(element, 'time', '14:30');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        const save = http.expectOne(base + '/lessons/l1');
        expect(save.request.body).toEqual({ title: 'Коллекции', date: '2026-10-02', time: '14:30', duration: 60, homeworkDue: null, revision: 5 });
        save.flush({ ...lesson, time: '14:30', revision: 6 });
        await renderResources(); fixture.detectChanges();
        expect(element.querySelector('.context-title .meta')?.textContent).toContain('14:30');
        flushTurns(http); http.verify();
    });
    it('creates a lesson with a homework deadline at 23:59 by default', async () => {
        const { fixture, http, element } = await open('/teacher/students/s1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons?page=0&size=25').flush(page([]));
        await renderResources(); fixture.detectChanges();
        http.expectOne(base + '/access').flush({ account: null, invitation: null });
        await renderResources(); fixture.detectChanges();
        click(element, 'Добавить занятие');
        fixture.detectChanges();
        expect(element.querySelector('.due-fields legend')?.textContent).toContain('Срок домашней работы');
        fill(element, 'title', 'Со сроком');
        fill(element, 'date', '2026-10-03');
        fill(element, 'time', '13:00');
        fill(element, 'dueDate', '2026-10-05');
        fixture.detectChanges();
        expect(element.querySelector('.due-actions button')?.textContent).toContain('Убрать срок');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        const create = http.expectOne(base + '/lessons');
        expect(create.request.body).toEqual({ title: 'Со сроком', date: '2026-10-03', time: '13:00', duration: 60, homeworkDue: { date: '2026-10-05', time: '23:59' } });
        create.flush({ message: 'stop here' }, { status: 503, statusText: 'Unavailable' });
        flushTurns(http); http.verify();
    });
    it('creates a lesson on the basis of this one for another card and opens it with a one-time notice', async () => {
        const { fixture, http, element, router } = await open('/teacher/students/s1/lessons/l1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons/l1').flush({ ...lesson, number: 7, studentNotes: '   ' });
        await renderResources(); fixture.detectChanges();
        click(element, 'Создать на основе');
        fixture.detectChanges();
        await renderResources();
        http.expectOne('/api/v1/workspaces/w1/students?page=0&size=25').flush(page([student, { ...student, id: 's2', name: 'Борис' }]));
        http.expectOne(base + '/lessons/l1/practice').flush({ revision: 2, exercises: [{}, {}, {}] });
        await renderResources(); fixture.detectChanges();
        expect(element.querySelector('#lesson-form-title')?.textContent).toBe('Новое занятие на основе № 7');
        expect((element.querySelector('[name="title"]') as HTMLInputElement).value).toBe('Коллекции');
        const summary = element.querySelector('.copy-summary')!.textContent!;
        expect(summary).toContain('Сценарий преподавателя');
        expect(summary).toContain('Задания ученика — пусто');
        expect(summary).toContain('Упражнения тренажёра: 3');
        expect(summary).toContain('Материалы, работы, ревью, отметка «Проведено» и срок ДЗ не копируются.');
        const select = element.querySelector('select[name="targetStudent"]') as HTMLSelectElement;
        expect([...select.options].map(option => option.textContent)).toEqual([student.name, 'Борис']);
        select.value = 's2'; select.dispatchEvent(new Event('change'));
        fill(element, 'date', '2026-10-20');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        const create = http.expectOne('/api/v1/workspaces/w1/students/s2/lessons');
        expect(create.request.body).toEqual({ title: 'Коллекции', date: '2026-10-20', time: '12:00', duration: 60, source: { studentId: 's1', lessonId: 'l1' } });
        const navigation = firstValueFrom(router.events.pipe(filter(event => event instanceof NavigationEnd)));
        create.flush({ ...lesson, id: 'l9', studentId: 's2', number: 1, reviewNotes: '' }, { status: 201, statusText: 'Created' });
        await navigation;
        await renderResources(); fixture.detectChanges();
        expect(router.url).toBe('/teacher/students/s2/lessons/l9');
        http.expectOne('/api/v1/workspaces/w1/students/s2').flush({ ...student, id: 's2', name: 'Борис' });
        http.expectOne('/api/v1/workspaces/w1/students/s2/lessons/l9').flush({ ...lesson, id: 'l9', studentId: 's2' });
        await renderResources(); fixture.detectChanges();
        expect(element.querySelector('.success-banner')?.textContent).toBe('Занятие создано на основе № 7. Добавьте материалы, когда будут готовы.');
        flushTurns(http); http.verify();
    });
    it('keeps a deadline before the lesson start local and removes a deadline with null', async () => {
        const { fixture, http, element } = await open('/teacher/students/s1/lessons/l1');
        http.expectOne(base).flush(student);
        http.expectOne(base + '/lessons/l1').flush({ ...lesson, revision: 5, homeworkDue: { date: '2026-10-04', time: '20:00', state: 'open' } });
        await renderResources(); fixture.detectChanges();
        click(element, 'Изменить занятие');
        fixture.detectChanges();
        expect((element.querySelector('[name="dueDate"]') as HTMLInputElement).value).toBe('2026-10-04');
        expect((element.querySelector('[name="dueTime"]') as HTMLInputElement).value).toBe('20:00');
        fill(element, 'dueDate', '2026-10-01');
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        http.expectNone(request => request.method === 'PATCH');
        expect(element.querySelector('#lesson-due-error')?.textContent).toBe('Срок не может быть раньше начала занятия.');
        expect(element.querySelector('[name="dueDate"]')?.getAttribute('aria-invalid')).toBe('true');
        click(element, 'Убрать срок');
        fixture.detectChanges();
        element.querySelector('form')!.dispatchEvent(new Event('submit'));
        fixture.detectChanges();
        const save = http.expectOne(base + '/lessons/l1');
        expect(save.request.body).toEqual({ title: 'Коллекции', date: '2026-10-02', time: '12:00', duration: 60, homeworkDue: null, revision: 5 });
        save.flush({ ...lesson, revision: 6 });
        await renderResources(); fixture.detectChanges();
        flushTurns(http); http.verify();
    });
});
